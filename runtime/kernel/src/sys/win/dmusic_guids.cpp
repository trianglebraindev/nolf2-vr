//------------------------------------------------------------------
//
//  MODULE  : DMUSIC_GUIDS.CPP
//
//  PURPOSE : Definitions of the DirectMusic interface and class IDs
//            the engine's music code uses.
//
//  WHY     : The DirectMusic headers only DECLARE these IDs. Their
//            definitions used to ship in dxguid.lib, but Microsoft
//            dropped DirectMusic from dxguid.lib along with the
//            headers. Windows still provides the DirectMusic runtime,
//            and it identifies its objects by these exact numbers, so
//            we define them here ourselves.
//
//            The values are fixed public COM identifiers (the same
//            numbers Microsoft's original headers contain).
//
//------------------------------------------------------------------

